def t(key, **kwargs):
    """Text for the current language; lists are returned as they are.
    With a target, {a} in the text becomes the English article for it: "a" or "an"."""
    if "target" in kwargs:
        kwargs.setdefault("a", "an" if kwargs["target"][:1].lower() in "aeiou" else "a")
    value = TEXTS[LANG["current"]][key]
    return value.format(**kwargs) if kwargs and isinstance(value, str) else value


def object_name(english_name):
    if LANG["current"] == "nl":
        return OBJECT_NAMES_NL.get(english_name, english_name)
    return english_name


